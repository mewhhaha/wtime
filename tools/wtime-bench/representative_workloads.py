def _signed_i32(value: int) -> int:
    value &= 0xFFFF_FFFF
    return value - 0x1_0000_0000 if value & 0x8000_0000 else value


def _fnv1a_i32(items: list[int]) -> int:
    value = 2166136261
    for item in items:
        value = ((value ^ item) * 16777619) & 0xFFFF_FFFF
    return _signed_i32(value)


def oracle(workload_id: str, size: int) -> dict[str, Any]:
    """Return a scalar result plus SHA-256 of the independently modeled output."""
    if workload_id not in KERNELS:
        workload_id = next((family for family, kernel in KERNELS.items()
                            if any(workload_id == f"{family}_{case}"
                                   for case in kernel["cases"])), workload_id)
    if workload_id not in KERNELS:
        raise ValueError(f"unknown representative workload: {workload_id}")
    allowed_sizes = set(KERNELS[workload_id]["cases"].values())
    if type(size) is not int or size not in allowed_sizes:
        raise ValueError(f"{workload_id} size must be one of {sorted(allowed_sizes)}")

    if workload_id == "representative_parser_hash":
        source = bytes(48 + ((index * 17 + 3) % 10) for index in range(size))
        parsed = bytes(character - 48 for character in source)
        result = _fnv1a_i32(list(parsed))
        output = parsed
    elif workload_id == "representative_image_filter":
        source = [(index * 37 + 11) & 0xFF for index in range(size)]
        output = bytes(
            (source[max(0, index - 1)] + source[index]
             + source[min(size - 1, index + 1)]) // 3
            for index in range(size)
        )
        result = sum(output)
    else:
        visited = {0}
        queue = [0]
        order: list[int] = []
        head = 0
        while head < len(queue):
            vertex = queue[head]
            head += 1
            order.append(vertex)
            neighbors = {(vertex + 1) % size, (vertex + 3) % size}
            for neighbor in range(size):
                if neighbor in neighbors and neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)
        output = bytes(order)
        result = _fnv1a_i32(order)

    return {
        "result": result,
        "output_sha256": hashlib.sha256(output).hexdigest(),
        "output_bytes": len(output),
    }


def expected_memory_image(workload_id: str, size: int) -> bytes:
    """Build the independent full 64 KiB memory image after prepare and run."""
    oracle(workload_id, size)  # Validate family and frozen input size first.
    memory = bytearray(65_536)
    if workload_id.startswith("representative_parser_hash"):
        source = bytes(48 + ((index * 17 + 3) % 10) for index in range(size))
        parsed = bytes(character - 48 for character in source)
        memory[:size] = source
        memory[4096:4096 + size] = parsed
    elif workload_id.startswith("representative_image_filter"):
        source = bytes((index * 37 + 11) & 0xFF for index in range(size))
        output = bytes((source[max(0, i - 1)] + source[i]
                        + source[min(size - 1, i + 1)]) // 3
                       for i in range(size))
        memory[:size] = source
        memory[4096:4096 + size] = output
    else:
        order: list[int] = []
        visited = {0}
        queue = [0]
        head = 0
        while head < len(queue):
            vertex = queue[head]
            head += 1
            order.append(vertex)
            neighbors = {(vertex + 1) % size, (vertex + 3) % size}
            for neighbor in range(size):
                if neighbor in neighbors and neighbor not in visited:
                    visited.add(neighbor)
                    queue.append(neighbor)
        memory[:size] = bytes(1 if i in visited else 0 for i in range(size))
        for index, vertex in enumerate(queue):
            start = 128 + index * 4
            memory[start:start + 4] = vertex.to_bytes(4, "little")
        memory[4096:4096 + len(order)] = bytes(order)
    return bytes(memory)


def provenance() -> dict[str, Any]:
    """Describe source ownership and the exact local encoding tool identity."""
    kernels = {}
    for workload_id, kernel in KERNELS.items():
        source = FIXTURE_DIR / kernel["file"]
        kernels[workload_id] = {
            "source": f"fixtures/representative/{kernel['file']}",
            "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
            "wasm_sha256": WASM_SHA256[kernel["file"]],
            "origin": "original WAT authored for the wtime performance fixture set",
            "license": "CC0-1.0",
            "external_source_or_download": False,
            "encoder": ENCODER_NAME,
            "encoder_sha256": ENCODER_SHA256,
            "encoding_command": ENCODING_COMMAND,
        }
    return {
        "kernels": kernels,
        "toolchain_notes": "Readable original WAT avoids an external compiler and moving benchmark suite; output bytes are produced by the pinned existing encoder.",
    }


